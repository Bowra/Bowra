def initial_schema(target: str) -> str:
    """Return the exact DDL snapshot for one 1.0.0 SQLite target."""
    try:
        encoded = INITIAL_SCHEMA_B85[target]
    except KeyError as exc:
        msg = f"unknown migration target: {target}"
        raise ValueError(msg) from exc
    schema = zlib.decompress(base64.b85decode(encoded)).decode()
    virtual_tables = re.findall(r"CREATE VIRTUAL TABLE(?: IF NOT EXISTS)? ['\"]?([^ '\"]+)", schema)
    statements = schema.split(";\n")
    schema = ";\n".join(
        statement
        for statement in statements
        if not any(re.match(rf"CREATE TABLE ['\"]?{re.escape(name)}_", statement) for name in virtual_tables)
    )
    return re.sub(
        r"(?m)^CREATE (TABLE|VIRTUAL TABLE|INDEX|UNIQUE INDEX|TRIGGER) (?!IF NOT EXISTS)",
        r"CREATE \1 IF NOT EXISTS ",
        schema,
    )
