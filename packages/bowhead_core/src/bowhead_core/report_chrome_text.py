def chrome_lang(language_context: Any) -> str:
    """Use the pinned output language, then the context, then English."""
    from bowhead_core.effective_language import language_decision_v2_enabled

    if language_decision_v2_enabled():
        from bowhead_core.agents._lead_context import get_current_output_language

        pinned = get_current_output_language()
        if pinned in _CHROME:
            return pinned
    lang = str(getattr(language_context, "output_language", "") or "")
    return lang if lang in _CHROME else "en-US"


def chrome_text(key: str, lang: str, **fmt: Any) -> str:
    """Render report copy; unsupported locales use English and unknown keys raise."""
    table = _CHROME.get(lang) or _CHROME["en-US"]
    if key == "generated_by":
        return table[key].format(product=product_name())
    return table[key].format(**fmt) if fmt else table[key]
