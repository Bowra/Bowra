"""Product display metadata affects generated chrome, never authored text."""

import json

import pytest
from bowhead_core.report_chrome_text import chrome_text

from bowhead_core import product_identity


@pytest.mark.parametrize("name", ["Bowhead", "Bowra"])
@pytest.mark.parametrize(
    ("locale", "template"),
    [
        ("en-US", "Generated by {}"),
        ("zh-CN", "{} 生成"),
        ("de-DE", "Erstellt von {}"),
        ("fr-FR", "Généré par {}"),
    ],
)
def test_report_signature_uses_fixed_product_identity(tmp_path, monkeypatch, name, locale, template):
    identity = tmp_path / "product_identity.json"
    identity.write_text(json.dumps({"schema_version": 1, "product_name": name}), encoding="utf-8")
    monkeypatch.setattr(product_identity, "PRODUCT_IDENTITY_PATH", identity)

    assert chrome_text("generated_by", locale) == template.format(name)
    assert "Bowhead Customer" in chrome_text("doc_figure_caption", locale, n=1, caption="Bowhead Customer")


@pytest.mark.parametrize("identity", [{}, {"schema_version": 1, "product_name": "unknown"}])
def test_invalid_product_metadata_is_an_installation_error(tmp_path, monkeypatch, identity):
    path = tmp_path / "product_identity.json"
    path.write_text(json.dumps(identity), encoding="utf-8")
    monkeypatch.setattr(product_identity, "PRODUCT_IDENTITY_PATH", path)
    with pytest.raises(ValueError, match="Unsupported Core product identity"):
        product_identity.product_name()
