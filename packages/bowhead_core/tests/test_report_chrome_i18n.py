def test_fabrication_caveat_localized_and_filter_bilingual() -> None:
    """dogfood t_ea634e084407：全英文报告里唯剩「数据可信度提示」块中文——守卫指控
    句在 en 轮也得英文。⚠前缀是 provenance_caveats 的识别标记且随 payload 落库：
    filter 必须双语种认（老 zh caveat 永续在库）。"""
    from bowhead_core.analysis_payload import (
        check_fabrication_back_reference,
        provenance_caveats,
    )

    payload = {"kpis": [{"label": "x", "value": "134.04"}], "exec_summary": ""}
    en = check_fabrication_back_reference(payload, {1.0}, lang="en-US")
    assert en and en[0].startswith("The following values could not be matched")
    assert "134.04 in KPI 1" in en[0]
    zh = check_fabrication_back_reference(payload, {1.0}, lang="zh-CN")
    assert zh and zh[0].startswith("以下数值在工具结果中未找到对应来源")
    # No language → English fallback.
    assert check_fabrication_back_reference(payload, {1.0}) == en
    assert "KPI 1 的 134.04" in zh[0]
    # Filter recognizes both languages.
    assert provenance_caveats({"caveats": en}) == en
    assert provenance_caveats({"caveats": zh}) == zh


