def test_composer_caveats_and_sources_localized() -> None:
    """局限段的本地化。★作者自己写的局限已交回正文（tech-design-document-minimalism §2.3），
    仍会渲的是**系统生成**的那两类，本地化风险一模一样——所以这里用 plan 缺腿提示触发同一段。"""
    from bowhead_core.analysis_payload import PLAN_GAP_CAVEAT_PREFIX as _GAP

    payload = {
        "caveats": [_GAP + "the compute step failed; this report omits its analysis"],
        "sources": [{"label": "bi", "tool": "bi_query", "artifact_id": "art_1"}],
    }
    en_secs = _build_sections_from_payload(payload, None, lang="en-US")
    kinds = {s["kind"]: s for s in en_secs}
    assert kinds["narrative"]["markdown"].startswith("**Data limitations / notes**")
    assert kinds["sources"]["label"] == "Data sources"
    zh_secs = _build_sections_from_payload(payload, None, lang="zh-CN")
    zk = {s["kind"]: s for s in zh_secs}
    assert zk["narrative"]["markdown"].startswith("**数据局限性 / 注意事项**")
    assert zk["sources"]["label"] == "数据来源"
    de_secs = _build_sections_from_payload(payload, None, lang="de-DE")
    dk = {s["kind"]: s for s in de_secs}
    assert dk["narrative"]["markdown"].startswith("**Dateneinschränkungen / Hinweise**")
    assert dk["sources"]["label"] == "Datenquellen"


