export function documentErrorKey(code?: string | null): string {
  return code && Object.hasOwn(errors, code) ? errors[code] : "error_generic";
}

/** A terminal failure is different from an uncertain confirmation response. */
export function documentFailureKey(code?: string | null): string {
  const key = documentErrorKey(code);
  return key === "error_generic" ? "canvas_failure_generic" : key;
}
