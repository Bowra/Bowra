def normalize_im_locale(value: object) -> str:
    """Project provider locale strings onto Bowhead's supported IM locales."""

    return resolve_presentation_locale(value)


def im_error_message(code: str, locale: object, **params: Any) -> str:
    """Render a finite message; unknown codes fail closed to a generic error."""

    normalized = normalize_im_locale(locale)
    table = IM_ERROR_MESSAGES[normalized]
    copy_code = clarification_failure_copy_code(code, params.get("diagnostics"))
    template = product_copy(table.get(copy_code, table["lead_internal_error"]))
    allowed = {field for _, field, _, _ in Formatter().parse(template) if field}
    safe_params = {key: _UNSAFE_PARAM_RE.sub(" ", str(value))[:120].strip() for key, value in params.items() if key in allowed}
    try:
        return template.format(**safe_params)
    except (KeyError, ValueError):
        return product_copy(table["lead_internal_error"])


def im_interface_message(key: str, locale: object, **params: Any) -> str:
    """Render finite IM interface copy without exposing provider errors."""
    template = product_copy(IM_INTERFACE_MESSAGES[normalize_im_locale(locale)][key])
    safe_params = {name: re.sub(r"[\x00-\x1f\x7f]", " ", str(value)) for name, value in params.items()}
    return template.format(**safe_params)


def im_error_labels(locale: object) -> dict[str, str]:
    return {key: product_copy(value) for key, value in IM_ERROR_LABELS[normalize_im_locale(locale)].items()}


def im_action_recorded(choice: object, locale: object) -> str:
    labels = im_error_labels(locale)
    safe_choice = _UNSAFE_PARAM_RE.sub(" ", str(choice))[:120].strip()
    return labels["action_recorded"].format(choice=safe_choice)


