def _shared_marketplace_messages(locales: tuple[str, ...]) -> dict[str, dict[str, str]]:
    # Read the tracked shared catalog: messages/<locale>.json is generated by
    # `make frontend-assemble` and is absent from a fresh checkout.
    repo_root = Path(__file__).resolve().parents[3]
    return {
        locale: json.loads(
            (repo_root / "packages" / "bowhead_frontend" / "edition" / "shared-messages" / f"{locale}.json").read_text(),
        )["agents_marketplace"]
        for locale in locales
    }


def test_search_index_matches_every_controlled_frontend_translation() -> None:
    messages = _shared_marketplace_messages(SYSTEM_AGENT_TEXT_LOCALES)
    for key, translations in MARKETPLACE_SEARCH_TEXT.items():
        assert set(SUPPORTED_MARKETPLACE_LOCALES) <= set(translations)
        for locale, value in translations.items():
            assert value == messages[locale][key], (key, locale)

    for system_name in listed_system_agents():
        search_text, _, _ = agents._system_item_index(
            {
                "agent_id": f"system:{system_name}",
                "display_name": system_name,
                "summary": system_name,
                "capabilities": [],
                "facets": {"domains": [], "jobs": [], "outputs": []},
            },
        )
        for key in system_agent_message_keys(system_name):
            for value in MARKETPLACE_SEARCH_TEXT[key].values():
                assert value.casefold() in search_text


def test_every_listed_system_agent_has_its_name_and_summary_in_four_locales() -> None:
    messages = _shared_marketplace_messages(SYSTEM_AGENT_TEXT_LOCALES)
    for system_name, listing in listed_system_agents().items():
        name_key, summary_key = system_agent_message_keys(system_name)
        # The manifest listing is the English source.
        assert messages["en-US"][name_key] == listing["display_name"]
        assert messages["en-US"][summary_key] == listing["summary"]
        for key in (name_key, summary_key):
            assert set(MARKETPLACE_SEARCH_TEXT[key]) == set(SYSTEM_AGENT_TEXT_LOCALES), key
            for locale in SYSTEM_AGENT_TEXT_LOCALES:
                assert messages[locale][key].strip(), (key, locale)

    for key, translations in MARKETPLACE_SEARCH_TEXT.items():
        if not key.startswith("cap_"):
            continue
        search_text, _, _ = agents._system_item_index(
            {
                "agent_id": "system:test",
                "display_name": "test",
                "summary": "test",
                "capabilities": [{"id": key, "category": "test"}],
                "facets": {"domains": [], "jobs": [], "outputs": []},
            },
        )
        for value in translations.values():
            assert value.casefold() in search_text


