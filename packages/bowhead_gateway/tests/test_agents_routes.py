def _enable_revisioned_agent(
    db_path,
    *,
    owner_user_id: str = "user_1",
    audience_mode: str = "private",
    tool_refs: tuple[str, ...] = (),
    audience_snapshot: dict | None = None,
) -> None:
    timestamp = "2026-09-03T00:00:00+00:00"
    definition = {
        "max_iterations": 10,
        "model": None,
        "output_schema": None,
        "skill_grants": [],
        "system_prompt": "Initial private instructions.",
        "tool_refs": list(tool_refs),
    }
    listing = {
        "description": "Monthly finance analysis",
        "display_name": "Finance Helper",
    }
    audience = (
        audience_snapshot
        if audience_snapshot is not None
        else {
            "effective_mode": audience_mode,
            "group_ids": [],
            "schema_version": 1,
            "user_ids": [],
        }
    )
    canonical_definition = json.dumps(
        definition,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    )
