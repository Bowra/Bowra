#!/usr/bin/env python3
"""Generate the frontend notification type table from the backend registry.

`bowhead_core.notification_types` is the single definition of every notification type. The
frontend reads its category, default priority, action classification and scope from the generated
`packages/bowhead_frontend/lib/notification-types.generated.ts`, and a frontend test requires copy
for every registered type. `--check` (run by `make lint`) fails when the generated file drifts.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TS_OUTPUT = ROOT / "packages/bowhead_frontend/lib/notification-types.generated.ts"

sys.path.insert(0, str(ROOT / "packages/bowhead_core/src"))

from bowhead_core.notification_types import REGISTRY  # noqa: E402


def _render() -> str:
    rows = []
    for type_ in sorted(REGISTRY):
        spec = REGISTRY[type_]
        key = type_ if type_.isidentifier() else json.dumps(type_)
        action = "true" if spec.action_required else "false"
        rows.append(
            f"  {key}: {{ category: {json.dumps(spec.category)}, priority: {json.dumps(spec.default_priority)}, "
            f"actionRequired: {action}, scope: {json.dumps(spec.scope)} }},"
        )
    body = "\n".join(rows)
    return (
        "// Generated by scripts/check_notification_types.py from bowhead_core.notification_types. Do not edit.\n"
        "\n"
        "export interface NotificationTypeEntry {\n"
        "  category: string;\n"
        '  priority: "p1" | "p2" | "p3";\n'
        "  actionRequired: boolean;\n"
        '  scope: "team" | "personal";\n'
        "}\n"
        "\n"
        "export const NOTIFICATION_TYPES: Readonly<Record<string, NotificationTypeEntry>> = {\n"
        f"{body}\n"
        "};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = _render()
    if args.write:
        TS_OUTPUT.write_text(expected, encoding="utf-8")
    else:
        actual = TS_OUTPUT.read_text(encoding="utf-8") if TS_OUTPUT.exists() else ""
        if actual != expected:
            sys.stderr.write(f"notification type table drift: run {Path(__file__).name} --write ({TS_OUTPUT.relative_to(ROOT)})\n")
            return 1
    sys.stdout.write(f"notification types: {len(REGISTRY)} registered\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
